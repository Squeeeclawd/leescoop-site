import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/lib/content.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText.replaceAll('import.meta.env.LEESCOOP_NOW', 'undefined');
const lib = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const article = (date, time, extra = {}) => ({ data: { date: new Date('2026-01-01T00:00:00Z'), draft: false, contentKind: 'event', eventDate: new Date(date), eventTime: time, ...extra } });
assert.equal(lib.leeCountyDateKey(new Date('2026-09-11T02:00:00Z')), '2026-09-10');
const summer = article('2026-09-19T10:00:00-04:00', '10:00 AM - 12:00 PM');
assert.equal(lib.eventArchiveCutoff(summer).toISOString(), '2026-09-19T16:00:00.000Z');
const winter = article('2026-12-12T17:00:00-05:00', '5:00 PM - 10:00 PM');
assert.equal(lib.eventArchiveCutoff(winter).toISOString(), '2026-12-13T03:00:00.000Z');
const doors = article('2026-10-18T13:00:00-04:00', 'Lobby 1:00 PM; concert 2:00 PM');
assert.equal(lib.eventArchiveCutoff(doors).toISOString(), '2026-10-19T03:59:59.999Z');
const overnight = article('2026-09-19T22:00:00-04:00', '10:00 PM - 1:00 AM');
assert.equal(lib.eventArchiveCutoff(overnight).toISOString(), '2026-09-20T05:00:00.000Z');
const spring = article('2026-03-08T10:00:00-04:00', '10:00 AM - 12:00 PM');
